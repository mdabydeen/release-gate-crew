package stub

import (
	"fmt"
	"regexp"
	"strings"
)

// Action is what the stub "model" does on one turn: call a tool or answer.
type Action struct {
	Tool string         `json:"tool,omitempty"`
	Args map[string]any `json:"args,omitempty"`
	Text string         `json:"text,omitempty"`
}

// IsToolCall reports whether the action is a tool call.
func (a Action) IsToolCall() bool { return a.Tool != "" }

func call(tool string, args map[string]any) Action { return Action{Tool: tool, Args: args} }
func say(text string) Action                       { return Action{Text: text} }

// Turn is everything a script needs to choose its next action.
type Turn struct {
	// Results holds the tool results returned since the agent's task began,
	// oldest first. len(Results) is the step number.
	Results []string
	// Task is the task text a parent delegated with transfer_task, if any.
	Task string
}

// Script plays one agent's fixed sequence of actions.
type Script func(Turn) Action

// Scripts maps the role marker in each prompt ("ROLE: <name>") to its script.
var Scripts = map[string]Script{
	"lead":              lead,
	"container_auditor": containerAuditor,
	"pipeline_auditor":  pipelineAuditor,
	"scribe":            scribe,
}

// FallbackText answers requests that carry no role marker, such as the
// runtime's session-title generation.
const FallbackText = "Release gate run"

// StubLabel prefixes every final answer so stub output is never mistaken for
// a real review.
const StubLabel = "[stub]"

func lead(t Turn) Action {
	switch len(t.Results) {
	case 0:
		return call("transfer_task", map[string]any{
			"agent":           "container_auditor",
			"task":            "Review target/Dockerfile and target/compose.yaml.",
			"expected_output": "Markdown list of findings with severity and file:line.",
		})
	case 1:
		return call("transfer_task", map[string]any{
			"agent":           "pipeline_auditor",
			"task":            "Review the workflow in target/ci/build.yml.",
			"expected_output": "Markdown list of findings with severity and file:line.",
		})
	case 2:
		return call("transfer_task", map[string]any{
			"agent": "scribe",
			"task": ScribeTaskPrefix + "\n\n## Container\n" + t.Results[0] +
				"\n\n## Pipeline\n" + t.Results[1],
			"expected_output": "Confirmation that the report was written.",
		})
	default:
		return say(StubLabel + " Gate run finished. Delegated to 3 sub-agents. " +
			"Report: reports/gate-report.md. The decision is not meaningful: " +
			"this run used the scripted stub model, not a real reviewer.")
	}
}

// ScribeTaskPrefix opens the task the lead delegates to the scribe.
const ScribeTaskPrefix = "Write reports/gate-report.md from these findings."

func containerAuditor(t Turn) Action {
	r := t.Results
	switch len(r) {
	case 0:
		return call("read_multiple_files", map[string]any{
			"paths": []string{"target/Dockerfile", "target/compose.yaml"},
		})
	case 1:
		return call("shell", map[string]any{
			"cmd": "grep -n -e FROM -e USER -e ENV -e privileged -e docker.sock " +
				"target/Dockerfile target/compose.yaml",
		})
	case 2:
		// .agentsignore must refuse this.
		return call("read_file", map[string]any{"path": "target/.env"})
	case 3:
		// A denied binary riding behind an allowed prefix. The strict deny
		// list blocks it; the naive-permissions flavor shows what happens
		// without it. curl --version makes no network call.
		return call("shell", map[string]any{"cmd": "grep -n FROM target/Dockerfile && curl --version"})
	default:
		return say(fmt.Sprintf("%s Harness check only, not a review.\n"+
			"- read Dockerfile + compose: %s\n"+
			"- grep matches:\n```\n%s\n```\n"+
			"- read target/.env: %s\n"+
			"- compound shell with curl: %s",
			StubLabel, okIf(strings.Contains(r[0], "FROM")),
			clip(r[1], 600), clip(r[2], 200), clip(r[3], 200)))
	}
}

func pipelineAuditor(t Turn) Action {
	r := t.Results
	switch len(r) {
	case 0:
		return call("read_file", map[string]any{"path": "target/ci/build.yml"})
	case 1:
		// Outside this agent's allow_list.
		return call("read_file", map[string]any{"path": "prompts/lead.md"})
	default:
		return say(fmt.Sprintf("%s Harness check only, not a review.\n"+
			"- read target/ci/build.yml: %s\n"+
			"- read prompts/lead.md (outside allow_list): %s",
			StubLabel, okIf(strings.Contains(r[0], "pull_request_target")), clip(r[1], 200)))
	}
}

func scribe(t Turn) Action {
	r := t.Results
	switch len(r) {
	case 0:
		findings := strings.TrimSpace(strings.TrimPrefix(t.Task, ScribeTaskPrefix))
		return call("write_file", map[string]any{
			"path": "reports/gate-report.md",
			"content": "# Release gate report\n\n" +
				"**Decision:** not meaningful (generated by the scripted stub model).\n\n" +
				findings + "\n",
		})
	case 1:
		// Outside this agent's allow_list.
		return call("write_file", map[string]any{"path": "target/Dockerfile", "content": "FROM scratch\n"})
	default:
		return say(StubLabel + " Wrote reports/gate-report.md.\n" +
			"- write target/Dockerfile (outside allow_list): " + clip(r[1], 200))
	}
}

var (
	roleRe = regexp.MustCompile(`ROLE:\s*(\w+)`)
	taskRe = regexp.MustCompile(`(?s)<task>\s*(.*?)\s*</task>`)
)

// Respond chooses the stub's action for a request.
//
// The agent is identified by the "ROLE: <name>" marker in its system prompt.
// The step is the number of tool results since the last user message.
// transfer_task delivers a sub-agent's task inside a <task> block in a system
// message, with a bare "Please proceed." user turn, so the task is read from
// there.
func Respond(req ChatRequest) Action {
	var system []string
	task := ""
	for _, m := range req.Messages {
		text := m.Text()
		if m.Role == "system" || m.Role == "developer" {
			system = append(system, text)
		}
		if task == "" {
			if found := taskRe.FindStringSubmatch(text); found != nil {
				task = found[1]
			}
		}
	}
	role := ""
	if found := roleRe.FindStringSubmatch(strings.Join(system, "\n")); found != nil {
		role = found[1]
	}
	script, ok := Scripts[role]
	if !ok {
		return say(FallbackText)
	}
	return script(Turn{Results: toolResults(req.Messages), Task: task})
}

// toolResults returns tool messages after the last user message, oldest first.
func toolResults(msgs []Message) []string {
	start := 0
	for i := len(msgs) - 1; i >= 0; i-- {
		if msgs[i].Role == "user" {
			start = i + 1
			break
		}
	}
	var out []string
	for _, m := range msgs[start:] {
		if m.Role == "tool" {
			out = append(out, m.Text())
		}
	}
	return out
}

func okIf(b bool) string {
	if b {
		return "ok"
	}
	return "FAILED"
}

func clip(s string, n int) string {
	s = strings.TrimSpace(s)
	if len(s) <= n {
		return s
	}
	return s[:n] + " ..."
}
